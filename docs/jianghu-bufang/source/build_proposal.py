def focus(path,x,y,w,h,box=None):
    path=Path(path);iw,ih=Image.open(path).size
    bx,by,bw,bh=box or (0,0,iw,ih)
    scale=max(w/bw,h/bh)
    dx=x+(w-bw*scale)/2-bx*scale
    dy=H-y-(h-bh*scale)/2+by*scale-ih*scale
    c.saveState();p=c.beginPath();p.rect(x,H-y-h,w,h);c.clipPath(p,stroke=0,fill=0)
    c.drawImage(ImageReader(str(path)),dx,dy,iw*scale,ih*scale,mask='auto');c.restoreState()

